/**
 * Minimal RFC 4180 CSV parser — quoted fields, escaped quotes ("" inside
 * quotes), commas and newlines inside quotes, CRLF/LF endings. No deps;
 * import files are small enough to parse in one pass off the UI thread.
 */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;
  let i = 0;

  const endField = () => {
    row.push(field);
    field = '';
  };
  const endRow = () => {
    endField();
    rows.push(row);
    row = [];
  };

  while (i < text.length) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i++;
        continue;
      }
      field += ch;
      i++;
      continue;
    }
    if (ch === '"' && field === '') {
      inQuotes = true;
      i++;
      continue;
    }
    if (ch === ',') {
      endField();
      i++;
      continue;
    }
    if (ch === '\r') {
      if (text[i + 1] === '\n') i++;
      endRow();
      i++;
      continue;
    }
    if (ch === '\n') {
      endRow();
      i++;
      continue;
    }
    field += ch;
    i++;
  }
  // Trailing field/row without final newline.
  if (field !== '' || row.length > 0) endRow();

  // Drop rows that are entirely empty (blank trailing lines).
  return rows.filter((r) => r.some((f) => f.trim() !== ''));
}
